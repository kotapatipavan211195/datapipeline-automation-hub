def copy_contacts_to_share(config_data):
    """Copy the contact files to the vendor share on the pipeline server"""

    logger.info(f'Function {copy_contacts_to_share.__name__} execution begin')

    start = time.perf_counter()

    # Break out configuration information
    file_copy = config_data.get('file_copy', {})
    sources = [source.format(date=date.today()) for source in file_copy.get('sources', [])]
    destination = file_copy.get('destination').format(date=date.today())

    # Google Cloud CLI: gcloud storage (the successor of gsutil)
    gcloud = shutil.which("gcloud")
    if gcloud is None:
        raise RuntimeError("gcloud CLI not found on PATH: install the Google Cloud CLI to use gcloud storage")
    cmd = [gcloud, "storage", 'cp', '--no-clobber', *sources, destination]
    try:
        logger.info(f"Running: gcloud storage cp --no-clobber {' '.join(sources)} {destination}")
        result = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", check=True)
        for line in (result.stderr + result.stdout).splitlines():
            if line.strip():
                logger.info(line.strip())

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {copy_contacts_to_share.__name__} execution end:  {execution_time} seconds.")
    except subprocess.CalledProcessError as e:
        raise RuntimeError(
            f"gcloud storage cp failed (exit code {e.returncode}): {(e.stderr or e.stdout or '').strip()}"
        )
    except Exception as e:
        s = str(e)
        raise RuntimeError(s)


def main(args):

    logger.info(f'Function {main.__name__} execution begin')
    logger.info(f'Parms-> Environment: {args.environment}')

    start = time.perf_counter()
    environment = args.environment
    config_file = args.cf
    schema_file = args.ts

    # global capture
    global capture
    capture = sql_logger.CaptureSQL(project_id, credentials, CONFIG["SCRIPT_NAME"], environment)

    # Get the context from config file.
    config_data = config.read_configuration(environment, config_file)
    logger.info(
        f"Parms-> Read project: {config_data.get('read_project')}  Write project: {config_data.get('write_project')}"
    )
    table_def = config.read_table_definition(schema_file)
    write_project = config_data.get('write_project')
    data_sets = config_data.get('data_sets', {})
    failed_steps = []

    try:
        # Step function calls go here
        # 1. Load the latest pipe-delimited CRM customer extract (.txt) into crm.customer_stg
        load_crm_customer_extract(config_data, table_def)

        # 2. Upsert staged customers into crm.dim_customer and log the change count
        merge_customer_dimension(write_project, data_sets)

        # 3. Publish the full customer dimension as Parquet for downstream teams
        try:
            publish_customer_snapshot(config_data)
        except Exception:
            logger.exception(
                f"Function {publish_customer_snapshot.__name__} failed; continuing with the next step"
            )
            failed_steps.append('publish_customer_snapshot')

        # 4. Write today's changed customer contacts as a pipe-delimited .txt file for the mailing vendor
        export_customer_contacts_txt(config_data)

        # (disabled in the hub) Rebuild the customer counts report table
        # refresh_customer_counts(write_project, data_sets)

        # 5. Copy the contact files to the vendor share on the pipeline server
        try:
            copy_contacts_to_share(config_data)
        except Exception:
            logger.exception(
                f"Function {copy_contacts_to_share.__name__} failed; continuing with the next step"
            )
            failed_steps.append('copy_contacts_to_share')

        if failed_steps:
            raise RuntimeError(f"Step(s) failed: {', '.join(failed_steps)}")
    finally:
        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {main.__name__} execution end:  {execution_time} seconds.")


