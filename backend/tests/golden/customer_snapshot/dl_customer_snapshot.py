def export_customer_contacts_txt(config_data):
    """
    Write today's changed customer contacts as a pipe-delimited .txt file for the mailing vendor

    Args:
        config_data (dict): Configuration data containing write project and GCS configuration.

    Returns:
        str: the gs:// path of the file(s) written.
    """
    logger.info(f'Function {export_customer_contacts_txt.__name__} execution begin')

    start = time.perf_counter()

    # Break out configuration information
    write_project = config_data.get('write_project')
    data_sets = config_data.get('data_sets', {})
    crm_dataset = data_sets.get('crm_dataset')
    ftp = config_data.get('ftp_contacts', {})
    gcs_write_bucket = ftp.get('bucket')
    gcs_write_path = ftp.get('path') or ''
    extract_file_name = ftp.get('file_name')

    extract_filename_suffix = date.today().strftime('%Y_%m_%d')
    extract_file_name = f"{extract_file_name}{extract_filename_suffix}-*.txt"
    object_name = f"{gcs_write_path.strip('/')}/{extract_file_name}" if gcs_write_path else extract_file_name
    destination_uri = f"gs://{gcs_write_bucket}/{object_name}"
    job_id = None
    try:
        sql = f"""
            SELECT customer_id, email, updated_at
            FROM `{write_project}.{crm_dataset}.dim_customer`
            WHERE DATE(updated_at) = @run_date
        """
        export_sql = f"EXPORT DATA OPTIONS (uri = '{destination_uri}', format = 'CSV', overwrite = true, header = true, field_delimiter = '|') AS\n{sql}"
        job_config = bigquery.QueryJobConfig(
            query_parameters=[
                bigquery.ScalarQueryParameter('run_date', 'DATE', date.today()),  # today's date
            ],
        )
        response = bq_client.query(export_sql, job_config=job_config)  # Google API to run SQL Code
        job_id = response.job_id
        response.result()  # Wait for complete
        capture.write_to_log(export_customer_contacts_txt.__name__, export_sql, "success", job_id)

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(
            f"Function {export_customer_contacts_txt.__name__} execution end:  {execution_time} seconds."
        )
        logger.info(f"Exported the query results to {destination_uri}")
        return destination_uri

    except Exception as e:
        capture.write_to_log(export_customer_contacts_txt.__name__, export_sql, "failure", job_id)
        s = str(e)
        raise RuntimeError(s)


