def publish_customer_snapshot(config_data):
    """
    Publish the full customer dimension as Parquet for downstream teams

    Args:
        config_data (dict): Configuration data containing write project and GCS configuration.

    Returns:
        str: the gs:// path of the file(s) written.
    """
    logger.info(f'Function {publish_customer_snapshot.__name__} execution begin')

    start = time.perf_counter()

    # Break out configuration information
    write_project = config_data.get('write_project')
    data_sets = config_data.get('data_sets', {})
    crm_dataset = data_sets.get('crm_dataset')
    ftp = config_data.get('ftp', {})
    gcs_write_bucket = ftp.get('bucket')
    gcs_write_path = ftp.get('path') or ''
    extract_file_name = ftp.get('file_name')

    extract_filename_suffix = date.today().strftime('%Y%m%d')
    extract_file_name = f"{extract_file_name}{extract_filename_suffix}-*.parquet"
    object_name = f"{gcs_write_path.strip('/')}/{extract_file_name}" if gcs_write_path else extract_file_name
    destination_uri = f"gs://{gcs_write_bucket}/{object_name}"

    source_table_id = f'{write_project}.{crm_dataset}.dim_customer'

    job_config = bigquery.ExtractJobConfig(
        destination_format=bigquery.DestinationFormat.PARQUET,
        compression=bigquery.Compression.SNAPPY,
    )
    try:
        extract_job = bq_client.extract_table(
            source_table_id,
            destination_uri,
            location='US',  # Specify your desired location
            job_config=job_config,
        )
        extract_job.result()

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(
            f"Function {publish_customer_snapshot.__name__} execution end:  {execution_time} seconds."
        )
        logger.info(f"Exported {source_table_id} to {destination_uri}")
        return destination_uri

    except Exception as e:
        s = str(e)
        raise RuntimeError(s)


