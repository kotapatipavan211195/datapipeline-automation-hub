    try:
        sql = f"""
            SELECT store_id, sale_date, total_amount, units
            FROM `{write_project}.{mart_dataset}.sales_daily`
            WHERE sale_date = @run_date
            ORDER BY store_id
        """
        export_sql = f"EXPORT DATA OPTIONS (uri = '{destination_uri}', format = 'CSV', overwrite = true, header = true, field_delimiter = ',', compression = 'GZIP') AS\n{sql}"
        job_config = bigquery.QueryJobConfig(
            query_parameters=[
                bigquery.ScalarQueryParameter(
                    'run_date', 'DATE', date.today() + timedelta(days=-1)
                ),  # today -1 day(s)
            ],
        )
        response = bq_client.query(export_sql, job_config=job_config)  # Google API to run SQL Code
        job_id = response.job_id
        response.result()  # Wait for complete
        capture.write_to_log(export_sales_daily_to_finance.__name__, export_sql, "success", job_id)

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(
            f"Function {export_sales_daily_to_finance.__name__} execution end:  {execution_time} seconds."
        )
        logger.info(f"Exported the query results to {destination_uri}")
        return destination_uri

    except Exception as e:
        capture.write_to_log(export_sales_daily_to_finance.__name__, export_sql, "failure", job_id)
        s = str(e)
        raise RuntimeError(s)


