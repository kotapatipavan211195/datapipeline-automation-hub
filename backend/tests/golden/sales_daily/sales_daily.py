def main(args):

    logger.info(f'Function {main.__name__} execution begin')
    logger.info(f'Parms-> Environment: {args.environment}')

    start = time.perf_counter()
    environment = args.environment
    config_file = args.cf
    schema_file = args.ts

    # global capture
    global capture
    capture = sql_logger.CaptureSQL(project_id, credentials, CONFIG["SCRIPT_NAME"], environment)

    # Get the context from config file.
    config_data = config.read_configuration(environment, config_file)
    logger.info(
        f"Parms-> Read project: {config_data.get('read_project')}  Write project: {config_data.get('write_project')}"
    )
    table_def = config.read_table_definition(schema_file)
    write_project = config_data.get('write_project')
    reference_project = config_data.get('reference_project')
    data_sets = config_data.get('data_sets', {})
    min_amount = config_data.get('min_amount')
    attachments = []

    try:
        # Step function calls go here
        # 1. Load the store sales CSV files for the run date into raw_sales.store_sales
        ingest_store_sales_files(config_data, table_def, environment)

        # 2. MERGE the day's raw sales into sales_mart.sales_daily (one row per store per day)
        build_sales_daily_agg(write_project, reference_project, data_sets, min_amount)

        # 3. Export the day's sales mart rows to the finance bucket as gzip CSV
        attachments.append(export_sales_daily_to_finance(config_data))

        # 4. Row count, key columns not null, one row per store per day
        check_sales_daily_quality(write_project, data_sets)

        # email execution
        email(config_data, environment, "SUCCESS", attachments=attachments)
    except Exception:
        logger.exception(f"Function {main.__name__} failed")
        try:
            email(config_data, environment, "FAILED")
        except Exception:
            logger.exception("The failure email could not be sent")
        raise
    finally:
        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {main.__name__} execution end:  {execution_time} seconds.")


