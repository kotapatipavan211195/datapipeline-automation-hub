def build_prod_script_test(write_project, data_sets):
    """Rebuild prod_script_test from the latest online quote conversion predictions"""

    logger.info(f'Function {build_prod_script_test.__name__} execution begin')

    start = time.perf_counter()

    # Break out configuration information
    w_model_scores_dataset = data_sets.get('w_model_scores_dataset')
    strategic_dataset = data_sets.get('strategic_dataset')
    dest_table_id = f'{write_project}.{strategic_dataset}.prod_script_test'
    job_id = None
    try:
        sql = f"""
            create or replace table `{write_project}.{strategic_dataset}.prod_script_test` as
            select * from `{write_project}.{w_model_scores_dataset}.prediction_ins_auto_online_quote_conversion`
            where score_date >= @score_start
            limit 100
        """
        job_config = bigquery.QueryJobConfig(
            query_parameters=[
                bigquery.ScalarQueryParameter(
                    'score_start', 'DATE', date.today().replace(day=1)
                ),  # first day of this month
            ],
        )
        response = bq_client.query(sql, job_config=job_config)  # Google API to run SQL Code
        job_id = response.job_id
        response.result()  # Wait for complete
        capture.write_to_log(build_prod_script_test.__name__, sql, "success", job_id)

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {build_prod_script_test.__name__} execution end:  {execution_time} seconds.")
        # Code to get the results of the load... This is not necessary but nice to have to update logs
        table = bq_client.get_table(dest_table_id)  # Make an API request.
        logger.info(f"Loaded {table.num_rows:,} rows and {len(table.schema):,} columns to {dest_table_id}")
    except Exception as e:
        capture.write_to_log(build_prod_script_test.__name__, sql, "failure", job_id)
        s = str(e)
        raise RuntimeError(s)


#### Uploading files to gcs buckets using extract job config####
def extract_data_file_csv(config_data):
    """
    Extract the active members table to the FTP bucket as a dated comma-delimited .txt file

    Args:
        config_data (dict): Configuration data containing write project and GCS configuration.

    Returns:
        str: the gs:// path of the file(s) written.
    """
    logger.info(f'Function {extract_data_file_csv.__name__} execution begin')

    start = time.perf_counter()

    # Break out configuration information
    write_project = config_data.get('write_project')
    data_sets = config_data.get('data_sets', {})
    membership_dataset = data_sets.get('membership_dataset')
    ftp = config_data.get('ftp', {})
    gcs_write_bucket = ftp.get('bucket')
    gcs_write_path = ftp.get('path') or ''
    extract_file_name = ftp.get('file_name')

    extract_filename_suffix = date.today().strftime('%Y_%m_%d')
    extract_file_name = f"{extract_file_name}{extract_filename_suffix}.txt"
    object_name = f"{gcs_write_path.strip('/')}/{extract_file_name}" if gcs_write_path else extract_file_name
    destination_uri = f"gs://{gcs_write_bucket}/{object_name}"

    source_table_id = f'{write_project}.{membership_dataset}.ms_acq_dm_active_members'

    job_config = bigquery.ExtractJobConfig(
        field_delimiter=',',
        print_header=True,
        destination_format=bigquery.DestinationFormat.CSV,
    )
    try:
        extract_job = bq_client.extract_table(
            source_table_id,
            destination_uri,
            location='US',  # Specify your desired location
            job_config=job_config,
        )
        extract_job.result()

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {extract_data_file_csv.__name__} execution end:  {execution_time} seconds.")
        logger.info(f"Exported {source_table_id} to {destination_uri}")
        return destination_uri

    except Exception as e:
        s = str(e)
        raise RuntimeError(s)


# Email module
def stream_file(attachment):
    """Download one attachment (gs://bucket/path/file or a local file) and return (bytes, file name)."""
    logger.info(f"Attachment download begin: {attachment}")
    try:
        if attachment.startswith("gs://"):
            bucket_name, _, blob_name = attachment[len("gs://") :].partition("/")
            data = storage_client.bucket(bucket_name).blob(blob_name).download_as_bytes()
        else:
            with open(attachment, "rb") as attachment_file:
                data = attachment_file.read()
        logger.info("File has been downloaded")
        return data, os.path.basename(attachment)
    except Exception:
        logger.exception("Error occured while downloading the attachment")
        raise


def collect_attachments(paths):
    """Read every attachment; a * in a gs:// path attaches every matching file (sharded exports)."""
    files = []
    for path in paths:
        if path.startswith("gs://") and "*" in path:
            bucket_name, _, pattern = path[len("gs://") :].partition("/")
            prefix, _, suffix = pattern.partition("*")
            for blob in storage_client.list_blobs(bucket_name, prefix=prefix):
                if blob.name.endswith(suffix.replace("*", "")):
                    files.append(stream_file(f"gs://{bucket_name}/{blob.name}"))
        else:
            files.append(stream_file(path))
    return files


def send_email(sender_email, receiver_email, subject, body, attachments=None):
    """Send the email through the internal mail relay (behind the VPN: no login)."""
    logger.info("Executing Automated Email Begin")
    try:
        message = EmailMessage()
        message["From"] = sender_email
        message["To"] = ", ".join(receiver_email)
        message["Subject"] = subject
        message.set_content(body)
        for attachment_data, attachment_filename in attachments or []:
            message.add_attachment(
                attachment_data, maintype='application', subtype='octet-stream', filename=attachment_filename
            )

        smtp_server = 'smtp.example.com'
        smtp_port = 25

        with smtplib.SMTP(smtp_server, smtp_port) as server:
            server.starttls()
            server.send_message(message)
            logger.info("Executed Automated Email Send")
    except Exception:
        logger.exception("Error occured while sending the email")
        raise


def email(config_data, environment, status, message=None, attachments=None):
    """Build and send the notification email (the 'email' block of the YAML)."""

    # email parameters
    email_config = config_data.get('email', {})
    sender_email = email_config.get('sender')
    receiver_email = email_config.get('receiver')

    # attachment parameters
    attachment = list(email_config.get('attachment') or [])

    try:
        logger.info("Email configuration begin")
        tokens = {
            "status": status,
            "script": CONFIG["SCRIPT_NAME"],
            "process": 'strategic_template',
            "environment": environment,
            "date": date.today(),
        }
        subject = '{script} | {status} | {environment}'.format(**tokens)  # subject of the email
        if message is None:
            message = 'The active members extract for {date:%Y-%m-%d} is attached.'.format(**tokens)
        body = f"""Hello Team,

{message}

Regards,
The Data Engineering Team

This is an automated email message."""  # body of the email

        # For email with attachment
        files = collect_attachments(attachment + list(attachments or []))
        send_email(sender_email, receiver_email, subject, body, files)

        logger.info("Email configuration end")
    except Exception:
        logger.exception("Error occured while configuring the email")
        raise


