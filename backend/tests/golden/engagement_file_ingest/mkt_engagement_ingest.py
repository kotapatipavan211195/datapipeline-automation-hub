def process_file(file_obj, schema: dict, separator: str, header: str, skiprows: str) -> pd.DataFrame:
    """Read one file into a DataFrame typed by the table schema (plus the batch audit columns)."""
    logger.info(f"Processing file: {file_obj.name}")
    content = io.StringIO(file_obj.download_as_text().encode('utf-8', 'ignore').decode('utf-8'))
    cols = list(schema.keys())
    type_map = {
        "string": "string",
        "int64": "int64",
        "integer": "Int64",
        "float": "float64",
        "float64": "float64",
        "boolean": "boolean",
        "bool": "boolean",
    }
    dtype = {}
    parse_dates = []
    date_cols = []
    numeric_cols = []
    for col_name, col_type in schema.items():
        col_type_lower = col_type.lower()
        if col_type_lower in ["datetime", "timestamp", "date"]:
            parse_dates.append(col_name)
            if col_type_lower == "date":
                date_cols.append(col_name)
        elif col_type_lower in ["numeric", "bignumeric"]:
            dtype[col_name] = "string"
            numeric_cols.append(col_name)
        else:
            dtype[col_name] = type_map.get(col_type_lower, "string")

    df = pd.read_csv(
        content,
        names=cols,
        sep=separator,
        header=ast.literal_eval(str(header)) if str(header).lower() != "none" else None,
        skiprows=ast.literal_eval(str(skiprows)) if str(skiprows).lower() != "none" else None,
        dtype=dtype,
        parse_dates=parse_dates,
        date_format="%Y-%m-%d %H:%M:%S",
        low_memory=False,
        on_bad_lines="warn",
    )

    for col in parse_dates:
        if col in df.columns:
            df[col] = pd.to_datetime(df[col], errors='coerce')
            if pd.api.types.is_datetime64_any_dtype(df[col]):
                df[col] = df[col].dt.tz_localize(None)
                df[col] = df[col].astype('datetime64[us]')
    for col in date_cols:
        df[col] = df[col].dt.date
    for col in numeric_cols:
        df[col] = df[col].map(
            lambda value: decimal.Decimal(value) if isinstance(value, str) and value.strip() else None
        )

    for col, col_dtype in df.dtypes.items():
        if col_dtype == 'string':
            df[col] = df[col].fillna("")
        elif col_dtype.name == "Int64":
            df[col] = df[col].fillna(pd.NA)

    df["file_batch_id"] = str(uuid.uuid4())
    df["inserted_ts"] = pd.to_datetime(CONFIG["EXEC_DATETIME"])
    df["updated_ts"] = pd.to_datetime(CONFIG["EXEC_DATETIME"])
    df["file_name"] = os.path.basename(file_obj.name)

    return df


def load_to_bq(
    df, project, dataset_id, dataset_id_1, staging_table, history_table, schema, write_disposition
):
    """Load one file's rows into the staging table and append them to the history table."""
    table_id_stg = f"{project}.{dataset_id_1}.{staging_table}"
    job_config = bigquery.LoadJobConfig(
        schema=schema,
        write_disposition="WRITE_TRUNCATE",  # empties the staging table first (and creates it on the first run)
    )
    job = bq_client.load_table_from_dataframe(df, table_id_stg, job_config=job_config)
    job.result()
    logger.info(f"Loaded {len(df)} rows into staging table {table_id_stg}")

    table_id_his = f"{project}.{dataset_id}.{history_table}"
    logger.info(f"Appending current batch records to history table: {table_id_his}")
    history_job_config = bigquery.LoadJobConfig(
        schema=schema,
        write_disposition=write_disposition,
    )
    history_job = bq_client.load_table_from_dataframe(df, table_id_his, job_config=history_job_config)
    history_job.result()
    logger.info(f"Appended {len(df)} rows into history table {table_id_his}")


def merge_to_main_table(project, dataset, dataset_1, staging_table, target_table, schema_fields):
    """MERGE the staged rows into the target table: newest row per Client_Id (by Created) wins."""
    target = f"{project}.{dataset}.{target_table}"
    source = f"{project}.{dataset_1}.{staging_table}"
    logger.info(f"Target table name: {target}")
    logger.info(f"Source table name: {source}")

    key_columns = ['Client_Id']
    columns = [f.name for f in schema_fields] + ["file_batch_id", "inserted_ts", "updated_ts", "file_name"]
    update_expr = ",\n            ".join(
        f"T.`{c}` = S.`{c}`" for c in columns if c not in key_columns + ["inserted_ts"]
    )
    insert_columns = ", ".join(f"`{c}`" for c in columns)
    insert_values = ", ".join(f"S.`{c}`" for c in columns)

    # First run: create the target table with the staging table's columns
    bq_client.query(f"CREATE TABLE IF NOT EXISTS `{target}` LIKE `{source}`").result()

    query = f"""
    MERGE `{target}` T USING (
        SELECT *
        EXCEPT(rn)
        FROM (
            SELECT *,
                row_number() over(
                    PARTITION BY `Client_Id`
                    ORDER BY `Created` DESC
                ) AS rn
            FROM `{source}`
            WHERE upper(Campaign) NOT LIKE '%UAT%'
        )
        WHERE rn = 1
    ) S ON T.`Client_Id` = S.`Client_Id`
    WHEN MATCHED AND T.`Created` < S.`Created` THEN
        UPDATE SET {update_expr}
    WHEN NOT MATCHED THEN
        INSERT ({insert_columns})
        VALUES ({insert_values})
    """
    logger.info("Running merge query...")
    job = bq_client.query(query)
    job.result()
    capture.write_to_log(merge_to_main_table.__name__, query, "success", job.job_id)
    logger.info(f"Merge completed: {job.num_dml_affected_rows} rows changed in {target}")
    return job.num_dml_affected_rows


def archive_data_file(filename, gcs_bucket, gcs_archive_bucket, gcs_archive_folder):
    """Move a processed file to the archive folder (copy, then delete the original)."""
    source_bucket = storage_client.bucket(gcs_bucket)
    source_blob = source_bucket.blob(filename)
    archive_bucket = storage_client.bucket(gcs_archive_bucket)
    archive_name = f"{gcs_archive_folder.strip('/')}/{os.path.basename(filename)}"
    source_bucket.copy_blob(source_blob, archive_bucket, archive_name)
    source_blob.delete()
    logger.info(f"Archived {filename} -> gs://{gcs_archive_bucket}/{archive_name}")


def move_vendor_files(config_data):
    """Move today's engagement files from the vendor drop bucket to the landing folder"""

    logger.info(f'Function {move_vendor_files.__name__} execution begin')

    start = time.perf_counter()

    # Break out configuration information
    file_copy = config_data.get('file_copy', {})
    sources = file_copy.get('sources', [])
    destination = file_copy.get('destination')

    # Google Cloud CLI: gcloud storage (the successor of gsutil)
    gcloud = shutil.which("gcloud")
    if gcloud is None:
        raise RuntimeError("gcloud CLI not found on PATH: install the Google Cloud CLI to use gcloud storage")
    cmd = [gcloud, "storage", 'mv', '--no-clobber', *sources, destination]
    try:
        logger.info(f"Running: gcloud storage mv --no-clobber {' '.join(sources)} {destination}")
        result = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", check=True)
        for line in (result.stderr + result.stdout).splitlines():
            if line.strip():
                logger.info(line.strip())

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {move_vendor_files.__name__} execution end:  {execution_time} seconds.")
    except subprocess.CalledProcessError as e:
        raise RuntimeError(
            f"gcloud storage mv failed (exit code {e.returncode}): {(e.stderr or e.stdout or '').strip()}"
        )
    except Exception as e:
        s = str(e)
        raise RuntimeError(s)


def ingest_engagement_files(config_data, table_def, environment):
    """Load the engagement files into staging, history and the daily table, then archive them"""

    logger.info(f'Function {ingest_engagement_files.__name__} execution begin')

    start = time.perf_counter()

    # Read configurations and table definition from YAML files
    write_project = config_data["write_project"]
    gcs_config = config_data['gcs_config']
    read_bucket = gcs_config["gcs_read_bucket"]
    read_prefix = gcs_config["gcs_read_bucket_path"] or ""
    archive_bucket = gcs_config["gcs_archive_bucket"]
    archive_path = gcs_config["gcs_archive_bucket_path"]
    filename = gcs_config["filename"]
    header = gcs_config["header"]
    skiprows = gcs_config["skiprows"]
    separator = gcs_config["separator"]
    write_disposition = config_data.get("write_disposition", "WRITE_APPEND")
    dataset_id = config_data["datasets"]["target"]
    dataset_id_1 = config_data["datasets"]["temporary"]
    table_name = table_def["table_name"]
    table_schema_dict = table_def["table_schema"]
    bq_schema = [
        bigquery.SchemaField(col, dtype.upper(), mode="NULLABLE") for col, dtype in table_schema_dict.items()
    ]
    history_table = f"{table_name}_history"
    target_table = 'engagement_daily'

    try:
        files = list(storage_client.list_blobs(read_bucket, prefix=read_prefix))
        qualified_files = [
            f
            for f in files
            if filename in os.path.basename(f.name)
            and f.name.lower().endswith(('.csv',))
            and not (archive_bucket == read_bucket and f.name.startswith(archive_path.strip("/") + "/"))
        ]
        # Oldest upload first: the newest file is applied last
        qualified_files.sort(key=lambda f: (f.updated, f.name))
        if not qualified_files:
            logger.info("No valid files to process.")
            email(config_data, environment, "NO FILE", message=f"There is no {filename} file received today.")
        else:
            for file_obj in qualified_files:
                if file_obj.size > 0:
                    df = process_file(file_obj, table_schema_dict, separator, header, skiprows)
                    load_to_bq(
                        df,
                        write_project,
                        dataset_id,
                        dataset_id_1,
                        table_name,
                        history_table,
                        bq_schema,
                        write_disposition,
                    )
                    merge_to_main_table(
                        write_project, dataset_id, dataset_id_1, table_name, target_table, bq_schema
                    )
                    archive_data_file(file_obj.name, read_bucket, archive_bucket, archive_path)
                else:
                    archive_data_file(file_obj.name, read_bucket, archive_bucket, archive_path)
                    logger.info(f"Skipped empty file: {file_obj.name}")

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {ingest_engagement_files.__name__} execution end:  {execution_time} seconds.")
    except Exception as e:
        s = str(e)
        raise RuntimeError(s)


def check_engagement_daily(write_project):
    """Every client appears once in the daily table"""

    logger.info(f'Function {check_engagement_daily.__name__} execution begin')

    start = time.perf_counter()
    failed_checks = []
    try:
        # Check 1 (error): passes when the value == 0
        check_name = 'unique(Client_Id) on engagement_daily'
        sql = f"""
            SELECT COUNT(*) AS value,
              TO_JSON_STRING(ARRAY_AGG(STRUCT(`Client_Id`) LIMIT 5)) AS details
            FROM (
              SELECT `Client_Id`
              FROM `{write_project}.clubwide.engagement_daily`
              GROUP BY `Client_Id`
              HAVING COUNT(*) > 1
            )
        """
        response = bq_client.query(sql)  # Google API to run SQL Code
        rows = list(response.result())
        capture.write_to_log(f"{check_engagement_daily.__name__}_check_1", sql, "success", response.job_id)
        value = rows[0]["value"] if rows else None
        if value is not None and value == 0:
            logger.info(f"Data-quality check passed: {check_name} = {value}")
        else:
            logger.error(f"Data-quality check FAILED: {check_name} = {value} (expected == 0)")
            failed_checks.append(check_name)

        # Check 2 (warn): passes when the value == 0
        check_name = 'not_null(Client_Id, Created) on engagement_daily'
        sql = f"""
            SELECT COUNTIF(`Client_Id` IS NULL) + COUNTIF(`Created` IS NULL) AS value,
              TO_JSON_STRING(STRUCT(COUNTIF(`Client_Id` IS NULL) AS Client_Id, COUNTIF(`Created` IS NULL) AS Created)) AS details
            FROM `{write_project}.clubwide.engagement_daily`
        """
        response = bq_client.query(sql)  # Google API to run SQL Code
        rows = list(response.result())
        capture.write_to_log(f"{check_engagement_daily.__name__}_check_2", sql, "success", response.job_id)
        value = rows[0]["value"] if rows else None
        if value is not None and value == 0:
            logger.info(f"Data-quality check passed: {check_name} = {value}")
        else:
            logger.warning(
                f"Data-quality check failed (warning only): {check_name} = {value} (expected == 0)"
            )

        if failed_checks:
            raise RuntimeError(f"Data-quality check(s) failed: {', '.join(failed_checks)}")

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {check_engagement_daily.__name__} execution end:  {execution_time} seconds.")
    except Exception as e:
        s = str(e)
        raise RuntimeError(s)


# Email module
def send_email(sender_email, receiver_email, subject, body, attachments=None):
    """Send the email through the internal mail relay (behind the VPN: no login)."""
    logger.info("Executing Automated Email Begin")
    try:
        message = EmailMessage()
        message["From"] = sender_email
        message["To"] = ", ".join(receiver_email)
        message["Subject"] = subject
        message.set_content(body)
        for attachment_data, attachment_filename in attachments or []:
            message.add_attachment(
                attachment_data, maintype='application', subtype='octet-stream', filename=attachment_filename
            )

        smtp_server = 'smtp.example.com'
        smtp_port = 25

        with smtplib.SMTP(smtp_server, smtp_port) as server:
            server.starttls()
            server.send_message(message)
            logger.info("Executed Automated Email Send")
    except Exception:
        logger.exception("Error occured while sending the email")
        raise


def email(config_data, environment, status, message=None, attachments=None):
    """Build and send the notification email (the 'email' block of the YAML)."""

    # email parameters
    email_config = config_data.get('email', {})
    sender_email = email_config.get('sender')
    receiver_email = email_config.get('receiver')

    try:
        logger.info("Email configuration begin")
        tokens = {
            "status": status,
            "script": CONFIG["SCRIPT_NAME"],
            "process": 'engagement_file_ingest',
            "environment": environment,
            "date": date.today(),
        }
        subject = 'Engagement File Status | {status} | {environment}'.format(**tokens)  # subject of the email
        if message is None:
            message = 'The engagement file ingestion finished with status {status}.'.format(**tokens)
        body = f"""Hello Team,

{message}

Regards,
The Data Engineering Team

This is an automated email message."""  # body of the email

        send_email(sender_email, receiver_email, subject, body)

        logger.info("Email configuration end")
    except Exception:
        logger.exception("Error occured while configuring the email")
        raise


