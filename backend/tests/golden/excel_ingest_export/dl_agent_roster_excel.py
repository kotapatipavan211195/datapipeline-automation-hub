# Email module
def stream_file(attachment):
    """Download one attachment (gs://bucket/path/file or a local file) and return (bytes, file name)."""
    logger.info(f"Attachment download begin: {attachment}")
    try:
        if attachment.startswith("gs://"):
            bucket_name, _, blob_name = attachment[len("gs://") :].partition("/")
            data = storage_client.bucket(bucket_name).blob(blob_name).download_as_bytes()
        else:
            with open(attachment, "rb") as attachment_file:
                data = attachment_file.read()
        logger.info("File has been downloaded")
        return data, os.path.basename(attachment)
    except Exception:
        logger.exception("Error occured while downloading the attachment")
        raise


def collect_attachments(paths):
    """Read every attachment; a * in a gs:// path attaches every matching file (sharded exports)."""
    files = []
    for path in paths:
        if path.startswith("gs://") and "*" in path:
            bucket_name, _, pattern = path[len("gs://") :].partition("/")
            prefix, _, suffix = pattern.partition("*")
            for blob in storage_client.list_blobs(bucket_name, prefix=prefix):
                if blob.name.endswith(suffix.replace("*", "")):
                    files.append(stream_file(f"gs://{bucket_name}/{blob.name}"))
        else:
            files.append(stream_file(path))
    return files


def send_email(sender_email, receiver_email, subject, body, attachments=None):
    """Send the email through the internal mail relay (behind the VPN: no login)."""
    logger.info("Executing Automated Email Begin")
    try:
        message = EmailMessage()
        message["From"] = sender_email
        message["To"] = ", ".join(receiver_email)
        message["Subject"] = subject
        message.set_content(body)
        for attachment_data, attachment_filename in attachments or []:
            message.add_attachment(
                attachment_data, maintype='application', subtype='octet-stream', filename=attachment_filename
            )

        smtp_server = 'smtp.example.com'
        smtp_port = 25

        with smtplib.SMTP(smtp_server, smtp_port) as server:
            server.starttls()
            server.send_message(message)
            logger.info("Executed Automated Email Send")
    except Exception:
        logger.exception("Error occured while sending the email")
        raise


def email(config_data, environment, status, message=None, attachments=None):
    """Build and send the notification email (the 'email' block of the YAML)."""

    # email parameters
    email_config = config_data.get('email', {})
    sender_email = email_config.get('sender')
    receiver_email = email_config.get('receiver')

    # attachment parameters
    attachment = list(email_config.get('attachment') or [])

    try:
        logger.info("Email configuration begin")
        tokens = {
            "status": status,
            "script": CONFIG["SCRIPT_NAME"],
            "process": 'agent_roster_excel',
            "environment": environment,
            "date": date.today(),
        }
        subject = '{script} | {status} | {environment}'.format(**tokens)  # subject of the email
        if message is None:
            message = 'The agent roster was loaded; the active agents per office are attached (status {status}).'.format(
                **tokens
            )
        if FILE_SUMMARY:  # the files loaded and exported so far (also when a step failed)
            message = f"{message}\n\nFiles processed:\n" + "\n".join(f"- {line}" for line in FILE_SUMMARY)
        body = f"""Hello Team,

{message}

Regards,
The Data Engineering Team

This is an automated email message."""  # body of the email

        # For email with attachment
        files = collect_attachments(attachment + list(attachments or []))
        send_email(sender_email, receiver_email, subject, body, files)

        logger.info("Email configuration end")
    except Exception:
        logger.exception("Error occured while configuring the email")
        raise


def main(args):

    logger.info(f'Function {main.__name__} execution begin')
    logger.info(f'Parms-> Environment: {args.environment}')

    start = time.perf_counter()
    environment = args.environment
    config_file = args.cf
    schema_file = args.ts

    # global capture
    global capture
    capture = sql_logger.CaptureSQL(project_id, credentials, CONFIG["SCRIPT_NAME"], environment)

    # Get the context from config file.
    config_data = config.read_configuration(environment, config_file)
    logger.info(
        f"Parms-> Read project: {config_data.get('read_project')}  Write project: {config_data.get('write_project')}"
    )
    table_def = config.read_table_definition(schema_file)
    attachments = []

    try:
        # Step function calls go here
        # 1. Load the agent roster workbook into staging, history and the agent table, then archive it
        ingest_agent_roster(config_data, table_def)

        # 2. Send the active agents per office to the sales office as an Excel workbook
        attachments.append(export_active_agents_xlsx(config_data))

        # 3. Keep a full copy of the agent table as an Excel workbook
        export_agent_table_xlsx(config_data)

        # email execution
        email(config_data, environment, "SUCCESS", attachments=attachments)
    except Exception:
        logger.exception(f"Function {main.__name__} failed")
        try:
            email(config_data, environment, "FAILED")
        except Exception:
            logger.exception("The failure email could not be sent")
        raise
    finally:
        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {main.__name__} execution end:  {execution_time} seconds.")


