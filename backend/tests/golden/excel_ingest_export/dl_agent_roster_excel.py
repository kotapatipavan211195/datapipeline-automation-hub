def export_active_agents_xlsx(config_data):
    """
    Send the active agents per office to the sales office as an Excel workbook

    Args:
        config_data (dict): Configuration data containing write project and GCS configuration.

    Returns:
        str: the gs:// path of the file(s) written.
    """
    logger.info(f'Function {export_active_agents_xlsx.__name__} execution begin')

    start = time.perf_counter()

    # Break out configuration information
    write_project = config_data.get('write_project')
    data_sets = config_data.get('data_sets', {})
    target_dataset = data_sets.get('target_dataset')
    ftp = config_data.get('ftp', {})
    gcs_write_bucket = ftp.get('bucket')
    gcs_write_path = ftp.get('path') or ''
    extract_file_name = ftp.get('file_name')

    extract_filename_suffix = date.today().strftime('%Y%m%d')
    extract_file_name = f"{extract_file_name}{extract_filename_suffix}.xlsx"
    object_name = f"{gcs_write_path.strip('/')}/{extract_file_name}" if gcs_write_path else extract_file_name
    destination_uri = f"gs://{gcs_write_bucket}/{object_name}"
    job_id = None
    try:
        sql = f"""
            SELECT office, agent_id, agent_name, hire_date, quota, policies_sold
            FROM `{write_project}.{target_dataset}.agent_roster_current`
            WHERE active AND hire_date <= @as_of
            ORDER BY office, agent_name
        """
        job_config = bigquery.QueryJobConfig(
            query_parameters=[
                bigquery.ScalarQueryParameter('as_of', 'DATE', date.today()),  # today's date
            ],
        )
        response = bq_client.query(sql, job_config=job_config)  # Google API to run SQL Code
        job_id = response.job_id
        df = response.to_dataframe()  # waits for the query
        capture.write_to_log(export_active_agents_xlsx.__name__, sql, "success", job_id)
        if len(df) > 1048575:
            raise RuntimeError(f"{len(df)} rows do not fit in one Excel sheet (at most 1048575)")
        for col in df.columns:  # Excel has no time zones (TIMESTAMP is UTC) and no BigQuery date/time types
            if isinstance(df[col].dtype, pd.DatetimeTZDtype):
                df[col] = df[col].dt.tz_localize(None)
            elif df[col].dtype.name in ("dbdate", "dbtime"):
                df[col] = df[col].astype(object)
        buffer = io.BytesIO()
        df.to_excel(buffer, sheet_name='Active agents', index=False, header=True, engine="openpyxl")
        storage_client.bucket(gcs_write_bucket).blob(object_name).upload_from_string(
            buffer.getvalue(),
            content_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        )

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(
            f"Function {export_active_agents_xlsx.__name__} execution end:  {execution_time} seconds."
        )
        logger.info(f"Exported {len(df)} rows to {destination_uri}")
        FILE_SUMMARY.append(f"{len(df):,} rows exported to {destination_uri}")
        return destination_uri

    except Exception as e:
        capture.write_to_log(export_active_agents_xlsx.__name__, sql, "failure", job_id)
        s = str(e)
        raise RuntimeError(s)


