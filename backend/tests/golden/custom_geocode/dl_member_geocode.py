def refresh_member_addresses(read_project, write_project, data_sets):
    """Rebuild the table of active member addresses to geocode"""

    logger.info(f'Function {refresh_member_addresses.__name__} execution begin')

    start = time.perf_counter()

    # Break out configuration information
    member_dataset = data_sets.get('member_dataset')
    dest_table_id = f'{write_project}.{member_dataset}.member_addresses'
    job_id = None
    try:
        sql = f"""
            CREATE OR REPLACE TABLE `{write_project}.{member_dataset}.member_addresses` AS
            SELECT member_id, address_line, city, state, zip_code
            FROM `{read_project}.membership.members`
            WHERE status = 'ACTIVE'
        """
        response = bq_client.query(sql)  # Google API to run SQL Code
        job_id = response.job_id
        response.result()  # Wait for complete
        capture.write_to_log(refresh_member_addresses.__name__, sql, "success", job_id)

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {refresh_member_addresses.__name__} execution end:  {execution_time} seconds.")
        # Code to get the results of the load... This is not necessary but nice to have to update logs
        table = bq_client.get_table(dest_table_id)  # Make an API request.
        logger.info(f"Loaded {table.num_rows:,} rows and {len(table.schema):,} columns to {dest_table_id}")
    except Exception as e:
        capture.write_to_log(refresh_member_addresses.__name__, sql, "failure", job_id)
        s = str(e)
        raise RuntimeError(s)


def geocode_member_addresses(config_data):
    """
    Geocode the member addresses with the maps API and store latitude/longitude

    Args:
        config_data (dict): Configuration data; this step's settings are under 'geocode_config'.
    """
    logger.info(f'Function {geocode_member_addresses.__name__} execution begin')

    start = time.perf_counter()

    # Break out configuration information
    geocode_config = config_data.get('geocode_config', {})

    try:
        secret_list_key = geocode_config.get('secret_list_key', 'api_credentials')
        secret_value_key = geocode_config.get('secret_value_key', 'api')
        api_key = SECRETS['geocode_api_key'][secret_list_key][0].get(secret_value_key)
        if not api_key:
            raise ValueError("API key not found in secret payload. Check secret structure.")

        address_table = geocode_config['address_table']
        result_table = geocode_config['result_table']

        sql = f"""
            SELECT member_id, address_line, city, state, zip_code
            FROM `{address_table}`
        """
        rows = list(bq_client.query(sql).result())
        logger.info(f"{len(rows)} address(es) to geocode")

        results = []
        with requests.Session() as session:
            for row in rows:
                address = f"{row['address_line']}, {row['city']}, {row['state']} {row['zip_code']}"
                response = session.get(
                    geocode_config['geocode_url'], params={"address": address, "key": api_key}, timeout=30
                )
                response.raise_for_status()
                matches = response.json().get("results") or []
                if not matches:
                    logger.warning(f"No match for member {row['member_id']}")
                    continue
                location = matches[0]["geometry"]["location"]
                results.append(
                    {
                        "member_id": row["member_id"],
                        "latitude": location["lat"],
                        "longitude": location["lng"],
                        "geocoded_ts": datetime.now().isoformat(),
                    }
                )

        if results:
            errors = bq_client.insert_rows_json(result_table, results)
            if errors:
                raise RuntimeError(f"BigQuery rejected {len(errors)} row(s): {errors[:3]}")
        logger.info(f"Geocoded {len(results)} of {len(rows)} address(es) into {result_table}")

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {geocode_member_addresses.__name__} execution end:  {execution_time} seconds.")
    except Exception as e:
        s = str(e)
        raise RuntimeError(s)


def get_gsm_secret(gsm_project, secret, version="latest"):
    """
    Fetches a secret from Google Secret Manager with the team's gsm_module and returns its whole payload:
    a JSON payload as a dict (e.g. {"api_credentials": [{"api": "..."}]}), any other payload as text.
    The steps pick what they need from it (the keys come from their settings in the YAML).

    Args:
        gsm_project (str): Project that holds the secret (gsm_project of the environment).
        secret (str): Secret id.
        version (str): 'latest' or a version number.
    """
    start = time.perf_counter()
    logger.info(f'Function {get_gsm_secret.__name__} execution begin: {secret} (version {version})')

    try:
        secret_conn = gsm.google_secret(credentials, gsm_project)
        secret_conn.set_secret_name(secret)
        secret_conn.set_version(version)
        response = secret_conn.get_gsm_secret()

        payload = response.payload.data.decode("UTF-8")

        if not payload.strip():
            raise ValueError(f"Secret {secret} has an empty payload. Check secret structure.")

        try:
            secret_value = json.loads(payload)
        except ValueError:
            secret_value = payload

        execution_time = round(time.perf_counter() - start, 2)

        logger.info(f"Function {get_gsm_secret.__name__} execution end:  {execution_time} seconds.")
        return secret_value

    except Exception as e:
        logger.error(f"Failed to get secret {secret} from Secret Manager: {e}")
        raise RuntimeError(f"Could not retrieve secret {secret}. Reason: {e}") from e


